GREEN = RGBColor(0x12, 0xA1, 0x50)
INK = RGBColor(0x2F, 0x34, 0x40)


def to_docx(v, path):
    d = Document()
    for s in d.sections:
        s.top_margin = s.bottom_margin = Cm(1.4)
        s.left_margin = s.right_margin = Cm(1.6)
    st = d.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(10)
    st.font.color.rgb = INK

    def para(text="", size=10, bold=False, color=None, italic=False, space_after=2):
        p = d.add_paragraph()
        p.paragraph_format.space_after = Pt(space_after)
        if text:
            r = p.add_run(text)
            r.font.size = Pt(size); r.bold = bold; r.italic = italic
            if color: r.font.color.rgb = color
        return p

    def heading(text):
        p = para(text, 12.5, True, GREEN, space_after=3)
        p.paragraph_format.space_before = Pt(8)

    def bullet(text, label=None):
        p = d.add_paragraph(style="List Bullet")
        p.paragraph_format.space_after = Pt(1.5)
        if label:
            r = p.add_run(label + ": "); r.bold = True
        p.add_run(text)

    c = CONTACT
    para("Kobi Omenaka", 24, color=RGBColor(0x3B, 0x3F, 0x4C), space_after=0)
    para(v["title"], 14, color=GREEN, space_after=2)
    para(f"{c['email']} | {c['phone']} | {c['linkedin']} | {c['web']}", 9.5, space_after=0)
    para(c["where_fractional"] if v.get("mode") == "fractional" else c["where"], 9.5)
    heading("Professional Summary"); para(v["summary"])
    heading("Core Skills")
    for k in v["skills"]:
        label, items = SKILLS[k]; bullet(items, label)
    heading("Employment History")
    for r in roles(v):
        p = para(f"{r['co']} | {r['role']} | {r['where']} | {r['dates']}", 10, True, space_after=0)
        p.paragraph_format.space_before = Pt(5)
        if r.get("about"): para(r["about"], 9.5, italic=True, space_after=1)
        if r.get("intro"): para(r["intro"], space_after=1)
        for b in r["bullets"]: bullet(b)
    heading("Earlier Career"); para(ENGINEERING)
    heading("Education and Certifications")
    for e in EDUCATION: bullet(e)
    heading("Languages"); para(LANGUAGES)
    heading("Additional Information")
    for k in v["other"]: bullet(OTHER[k])
    bullet(OTHER_TAIL)
    d.save(path)


def to_pdf(html_path, pdf_path, tries=3):
    # Headless Chrome occasionally exits 2 on a busy machine; a fresh profile plus a retry clears it
    import tempfile
    for attempt in range(tries):
        with tempfile.TemporaryDirectory() as prof:
            r = subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                                f"--user-data-dir={prof}", f"--print-to-pdf={pdf_path}", "file://" + html_path],
                               capture_output=True, timeout=120)
        if r.returncode == 0:
            return
    raise RuntimeError(f"Chrome failed on {html_path}: {r.stderr.decode()[-300:]}")


def main(argv):
    only = None
    for a in argv:
        if a.startswith("--only"):
            only = argv[argv.index(a) + 1].split(",")
    os.makedirs(OUT, exist_ok=True)
    src = os.path.join(OUT, "_html"); os.makedirs(src, exist_ok=True)
    for key, v in VERSIONS.items():
        if only and key not in only:
            continue
        hp = os.path.join(src, v["file"] + ".html")
        with open(hp, "w") as f:
            f.write(to_html(v))
        to_docx(v, os.path.join(OUT, v["file"] + ".docx"))
        if "--no-pdf" not in argv:
            to_pdf(hp, os.path.join(OUT, v["file"] + ".pdf"))
        print("built", v["file"])


if __name__ == "__main__":
    main(sys.argv[1:])
